CREATE TABLE IF NOT EXISTS nft (ID INTEGER PRIMARY KEY ASC AUTOINCREMENT NOT NULL, hash TEXT NOT NULL,
        public_key TEXT, quantity INTEGER NOT NULL, fraction_numerator INTEGER,
        fraction_denominator INTEGER, consumed INTEGER NOT NULL, salt TEXT);
CREATE TABLE IF NOT EXISTS certificate (ID INTEGER PRIMARY KEY ASC AUTOINCREMENT NOT NULL,
        timestamp TEXT NOT NULL, body BLOB NOT NULL, hash TEXT UNIQUE);
CREATE TABLE IF NOT EXISTS trust_list (root TEXT NOT NULL, leafs BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS merkle_tree (root TEXT NOT NULL, leafs BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS test_entity (ID INTEGER PRIMARY KEY ASC AUTOINCREMENT NOT NULL,
        some_int INTEGER, some_string TEXT, some_bool INTEGER, some_blob BLOB, some_float REAL);
